/** 作品时间里每个图层画的是哪个场景、场景时间 = 作品时间 + shift（和各时间轴 visual.json 的图层一致） */
const SCENE_SPANS: [number, number, string, number][] = [
  [0, 16.8144, "act1", 0],
  [16.8144, 39.39, "act2", 0],
  [39.39, 72.019, "act3", 0],
  [72.019, 81.6, "act4", 0],
  [81.6, 82.0204, "act4", 6],
  [82.0204, 88.0204, "act5", 6],
  [88.0204, 91.99, "act5", 14],
  [91.99, 94.021, "act6", 14],
  [122.42, 125.523, "recall", 0],
  [94.021, 999, "finale", 0],
];
export function sceneAtWork(t: number): { scene: string; t: number } {
  for (const [a, b, scene, shift] of SCENE_SPANS) if (t >= a && t < b) return { scene, t: t + shift };
  return { scene: "finale", t };
}
/** 作品时间 t 画面上的横屏取景（叠在上面的东西跟着它换算） */
export function frameAtWork(t: number): Reframe {
  const s = sceneAtWork(t);
  return reframeAt(s.scene, s.t);
}
