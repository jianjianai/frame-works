/** 和 lib/end_cam.ts 第四声往后拉开的 pullCurve 一样：起步极轻（前 45% 慢慢加上来），之后越退越慢 */
const pullCurve = (u: number) => (1 - (1 - u) * (1 - u)) * E.soft(Math.min(1, u / 0.45));
const ease = (e: Ease | undefined, u: number) => {
  switch (e) {
    case "lin":
      return u;
    case "out":
      return E.out(u);
    case "in":
      return E.in2(u);
    case "soft":
      return E.soft(u);
    case "settle":
      return E.settle(u);
    case "pull":
      return pullCurve(u);
    default:
      return E.io(u);
  }
};

/** 这个场景这一刻的横屏取景 */
export function reframeAt(scene: string, t: number): Reframe {
  const keys = TRACKS[scene] ?? [[0, K0, 0, 0]];
  if (t <= keys[0][0]) return { k: keys[0][1], ox: keys[0][2], oy: keys[0][3] };
  for (let i = 1; i < keys.length; i++) {
    const b = keys[i];
    if (t >= b[0]) continue;
    const a = keys[i - 1];
    // 下一个关键帧是切点：这一段停在上一个关键帧
    if (b[4] === "cut") return { k: a[1], ox: a[2], oy: a[3] };
    // 从上一个关键帧的时刻起过渡，到这个关键帧的时刻到位
    const u = ease(b[4], Math.min(1, Math.max(0, (t - a[0]) / (b[0] - a[0]))));
    return { k: a[1] * Math.pow(b[1] / a[1], u), ox: a[2] + (b[2] - a[2]) * u, oy: a[3] + (b[3] - a[3]) * u };
  }
  const z = keys[keys.length - 1];
  return { k: z[1], ox: z[2], oy: z[3] };
}

/** 横屏专门写的镜头（不是换算竖屏的取景）：返回横屏画面上的镜头 */
const CUSTOM: Record<string, (t: number, c: Cam) => Cam | null> = {};

export function lensAt(scene: string, t: number): ((c: Cam) => Cam) | null {
  if (!LANDSCAPE) return null;
  const f = reframeAt(scene, t);
  const custom = CUSTOM[scene];
  return (c) => (custom && custom(t, c)) || reframe(c, f);
}

