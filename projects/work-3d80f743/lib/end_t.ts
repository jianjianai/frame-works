export const mix = (a: V2, b: V2, u: number): V2 => [a[0] + (b[0] - a[0]) * u, a[1] + (b[1] - a[1]) * u];
export const lerp = (a: number, b: number, u: number) => a + (b - a) * u;
/** 三次 Hermite（一维）：从 a（速度 va）到 b（速度 vb），用 dt 秒，u 是 0–1 的进度 */
export function herm(a: number, va: number, b: number, vb: number, dt: number, u: number) {
  const u2 = u * u;
  const u3 = u2 * u;
  return (2 * u3 - 3 * u2 + 1) * a + (u3 - 2 * u2 + u) * dt * va + (-2 * u3 + 3 * u2) * b + (u3 - u2) * dt * vb;
}
/** 三次 Hermite 的导数（每秒） */
export function hermV(a: number, va: number, b: number, vb: number, dt: number, u: number) {
  const u2 = u * u;
  return ((6 * u2 - 6 * u) * a + (3 * u2 - 4 * u + 1) * dt * va + (-6 * u2 + 6 * u) * b + (3 * u2 - 2 * u) * dt * vb) / dt;
}
/** 两段之间平滑地开关（0 → 1 → 0）：a–b 淡进，c–d 淡出 */
export function win(t: number, a: number, b: number, c: number, d: number) {
  const s = (x: number) => (x <= 0 ? 0 : x >= 1 ? 1 : x * x * (3 - 2 * x));
  return s((t - a) / (b - a)) * (1 - s((t - c) / (d - c)));
}
